import re


def normalize_kz_phone(raw: str) -> str:
    """
    Қазақстандық телефон нөмірін бірыңғай халықаралық форматқа (+7XXXXXXXXXX) келтіреді.

    Параметр:
        raw (str): Өңделетін бастапқы телефон нөмірі.

    Қайтарады:
        str: +7 форматындағы қалыпқа келтірілген нөмір.

    Қателер:
        ValueError: Нөмір дұрыс емес немесе жарамсыз болған жағдайда қазақша хабармен.
    """
    if not isinstance(raw, str):
        raise ValueError("Телефон нөмірі жол (string) түрінде берілуі тиіс")

    cleaned = raw.strip()
    if not cleaned:
        raise ValueError("Телефон нөмірі бос болмауы тиіс")

    # Тек рұқсат етілген таңбаларды тексеру: цифрлар, +, -, (, ), бос орындар
    if re.search(r"[^\d+\-\(\)\s]", cleaned):
        raise ValueError("Телефон нөмірінде жарамсыз таңбалар бар")

    # Тек цифрларды шығарып алу
    digits = re.sub(r"\D", "", cleaned)

    # Қазақстан нөмірлері 11 цифрдан тұруы керек
    if len(digits) != 11:
        raise ValueError("Телефон нөмірінің ұзындығы дұрыс емес (11 цифр болуы тиіс)")

    # Нөмір 8 немесе 7-ден басталуы керек
    if digits[0] not in ("7", "8"):
        raise ValueError("Қазақстан нөмірі 8 немесе +7 кодымен басталуы тиіс")

    return f"+7{digits[1:]}"

